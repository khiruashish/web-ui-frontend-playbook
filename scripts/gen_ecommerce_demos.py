#!/usr/bin/env python3
"""Generate the per-component demo pages of the E-commerce tab from the full store page.

docs/ecommerce/demos/store.html is the single source of truth for the markup. Each lesson shows one
component on its own, so this script cuts the marked sections (<!-- --8<-- [start:name] --> ...
[end:name]) out of store.html and wraps them in a minimal page with only the CSS that component needs.

    python3 scripts/gen_ecommerce_demos.py docs/ecommerce/demos

Edit store.html (or this script), never the generated NN-*.html files.
"""
import re
import sys
from pathlib import Path

# file name -> (title, stylesheets, sections, wrap sections in <main class="container">?, needs store.js?)
PAGES = {
    "02-header.html": ("Header", ["base", "header"], ["skiplink", "announcement", "header", "catnav"], False, False),
    "03-hero.html": ("Hero and categories", ["base", "home"], ["hero", "categories"], True, False),
    "04-product-card.html": ("Product card", ["base", "home", "product"], ["products"], True, True),
    "05-listing.html": ("Listing with filters", ["base", "home", "product", "listing"], ["listing"], True, True),
    "06-cart.html": (
        "Cart drawer",
        ["base", "header", "home", "product", "cart"],
        ["header", "products", "cart"],
        True,
        True,
    ),
    "07-footer.html": ("Footer and bottom nav", ["base", "footer"], ["footer", "bottomnav"], False, False),
}
MARKER = re.compile(r"^\s*<!-- --8<-- \[(start|end):[\w-]+\] -->\s*$")


def section(source: str, name: str) -> str:
    match = re.search(
        rf"^[ \t]*<!-- --8<-- \[start:{name}\] -->\n(.*?)^[ \t]*<!-- --8<-- \[end:{name}\] -->",
        source,
        re.S | re.M,
    )
    if not match:
        raise SystemExit(f"section '{name}' not found in store.html")
    lines = [line for line in match.group(1).splitlines() if not MARKER.match(line)]
    indent = min(len(line) - len(line.lstrip()) for line in lines if line.strip())
    return "\n".join(line[indent:] for line in lines)


def page(title, css, sections, wrap, js, source):
    body = "\n\n".join(section(source, name) for name in sections)
    if wrap:
        inner = "\n".join(("  " + line) if line else "" for line in body.splitlines())
        body = '<main id="main" class="container">\n' + inner + "\n</main>"
    if "products" in sections and "listing" not in sections:
        body = body.replace('<div class="product-grid"', '<div class="product-grid section"', 1)
    links = "\n".join(f'  <link rel="stylesheet" href="css/{name}.css">' for name in css)
    script = '\n  <script src="js/store.js" defer></script>' if js else ""
    indented = "\n".join(("  " + line) if line else "" for line in body.splitlines())
    return f"""<!doctype html>
<!-- Generated by scripts/gen_ecommerce_demos.py from store.html. Edit store.html, not this file. -->
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>FreshCart: {title}</title>
{links}{script}
</head>
<body>
{indented}
</body>
</html>
"""


def main(out_dir: str) -> None:
    out = Path(out_dir)
    source = (out / "store.html").read_text(encoding="utf-8")
    for name, spec in PAGES.items():
        (out / name).write_text(page(*spec, source), encoding="utf-8")
        print(f"wrote {out / name}")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "docs/ecommerce/demos")
